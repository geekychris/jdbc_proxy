package com.hitorro.jdbcproxy.driver;

import com.hitorro.jdbcproxy.hooks.ProxyConfiguration;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.sql.*;
import java.util.Collections;
import java.util.List;

/**
 * Base class for proxy statement implementations containing common functionality.
 */
public abstract class BaseProxyStatement<T extends Statement> implements Statement {

    private static final Logger logger = LoggerFactory.getLogger(BaseProxyStatement.class);

    protected final T underlyingStatement;
    protected final ProxyConnection proxyConnection;
    protected final ProxyConfiguration config;

    public BaseProxyStatement(T underlyingStatement, ProxyConnection proxyConnection, ProxyConfiguration config) {
        this.underlyingStatement = underlyingStatement;
        this.proxyConnection = proxyConnection;
        this.config = config;
    }

    @Override
    public ResultSet executeQuery(String sql) throws SQLException {
        return executeWithLogging(sql, () -> {
            String rewrittenSql = applySqlRewriting(sql);
            ResultSet underlyingResultSet = underlyingStatement.executeQuery(rewrittenSql);
            return new ProxyResultSet(underlyingResultSet, sql, proxyConnection, config);
        });
    }

    @Override
    public int executeUpdate(String sql) throws SQLException {
        return executeWithLogging(sql, () -> {
            String rewrittenSql = applySqlRewriting(sql);
            return underlyingStatement.executeUpdate(rewrittenSql);
        });
    }

    @Override
    public boolean execute(String sql) throws SQLException {
        return executeWithLogging(sql, () -> {
            String rewrittenSql = applySqlRewriting(sql);
            return underlyingStatement.execute(rewrittenSql);
        });
    }

    @Override
    public ResultSet getResultSet() throws SQLException {
        ResultSet underlyingResultSet = underlyingStatement.getResultSet();
        if (underlyingResultSet == null) {
            return null;
        }
        return new ProxyResultSet(underlyingResultSet, getLastExecutedSql(), proxyConnection, config);
    }

    @Override
    public int getUpdateCount() throws SQLException {
        return underlyingStatement.getUpdateCount();
    }

    @Override
    public boolean getMoreResults() throws SQLException {
        return underlyingStatement.getMoreResults();
    }

    @Override
    public void setFetchDirection(int direction) throws SQLException {
        underlyingStatement.setFetchDirection(direction);
    }

    @Override
    public int getFetchDirection() throws SQLException {
        return underlyingStatement.getFetchDirection();
    }

    @Override
    public void setFetchSize(int rows) throws SQLException {
        underlyingStatement.setFetchSize(rows);
    }

    @Override
    public int getFetchSize() throws SQLException {
        return underlyingStatement.getFetchSize();
    }

    @Override
    public int getResultSetConcurrency() throws SQLException {
        return underlyingStatement.getResultSetConcurrency();
    }

    @Override
    public int getResultSetType() throws SQLException {
        return underlyingStatement.getResultSetType();
    }

    @Override
    public void addBatch(String sql) throws SQLException {
        String rewrittenSql = applySqlRewriting(sql);
        underlyingStatement.addBatch(rewrittenSql);
    }

    @Override
    public void clearBatch() throws SQLException {
        underlyingStatement.clearBatch();
    }

    @Override
    public int[] executeBatch() throws SQLException {
        long startTime = System.currentTimeMillis();
        SQLException exception = null;
        int[] updateCounts = null;
        
        try {
            updateCounts = underlyingStatement.executeBatch();
            return updateCounts;
        } catch (SQLException e) {
            exception = e;
            throw e;
        } finally {
            long endTime = System.currentTimeMillis();
            logBatch(startTime, endTime, updateCounts, exception);
        }
    }

    @Override
    public Connection getConnection() throws SQLException {
        return proxyConnection;
    }

    @Override
    public boolean getMoreResults(int current) throws SQLException {
        return underlyingStatement.getMoreResults(current);
    }

    @Override
    public ResultSet getGeneratedKeys() throws SQLException {
        ResultSet underlyingResultSet = underlyingStatement.getGeneratedKeys();
        if (underlyingResultSet == null) {
            return null;
        }
        return new ProxyResultSet(underlyingResultSet, getLastExecutedSql(), proxyConnection, config);
    }

    @Override
    public int executeUpdate(String sql, int autoGeneratedKeys) throws SQLException {
        return executeWithLogging(sql, () -> {
            String rewrittenSql = applySqlRewriting(sql);
            return underlyingStatement.executeUpdate(rewrittenSql, autoGeneratedKeys);
        });
    }

    @Override
    public int executeUpdate(String sql, int[] columnIndexes) throws SQLException {
        return executeWithLogging(sql, () -> {
            String rewrittenSql = applySqlRewriting(sql);
            return underlyingStatement.executeUpdate(rewrittenSql, columnIndexes);
        });
    }

    @Override
    public int executeUpdate(String sql, String[] columnNames) throws SQLException {
        return executeWithLogging(sql, () -> {
            String rewrittenSql = applySqlRewriting(sql);
            return underlyingStatement.executeUpdate(rewrittenSql, columnNames);
        });
    }

    @Override
    public boolean execute(String sql, int autoGeneratedKeys) throws SQLException {
        return executeWithLogging(sql, () -> {
            String rewrittenSql = applySqlRewriting(sql);
            return underlyingStatement.execute(rewrittenSql, autoGeneratedKeys);
        });
    }

    @Override
    public boolean execute(String sql, int[] columnIndexes) throws SQLException {
        return executeWithLogging(sql, () -> {
            String rewrittenSql = applySqlRewriting(sql);
            return underlyingStatement.execute(rewrittenSql, columnIndexes);
        });
    }

    @Override
    public boolean execute(String sql, String[] columnNames) throws SQLException {
        return executeWithLogging(sql, () -> {
            String rewrittenSql = applySqlRewriting(sql);
            return underlyingStatement.execute(rewrittenSql, columnNames);
        });
    }

    @Override
    public int getResultSetHoldability() throws SQLException {
        return underlyingStatement.getResultSetHoldability();
    }

    @Override
    public boolean isClosed() throws SQLException {
        return underlyingStatement.isClosed();
    }

    @Override
    public void setPoolable(boolean poolable) throws SQLException {
        underlyingStatement.setPoolable(poolable);
    }

    @Override
    public boolean isPoolable() throws SQLException {
        return underlyingStatement.isPoolable();
    }

    @Override
    public void closeOnCompletion() throws SQLException {
        underlyingStatement.closeOnCompletion();
    }

    @Override
    public boolean isCloseOnCompletion() throws SQLException {
        return underlyingStatement.isCloseOnCompletion();
    }

    @Override
    public void close() throws SQLException {
        underlyingStatement.close();
    }

    @Override
    public int getMaxFieldSize() throws SQLException {
        return underlyingStatement.getMaxFieldSize();
    }

    @Override
    public void setMaxFieldSize(int max) throws SQLException {
        underlyingStatement.setMaxFieldSize(max);
    }

    @Override
    public int getMaxRows() throws SQLException {
        return underlyingStatement.getMaxRows();
    }

    @Override
    public void setMaxRows(int max) throws SQLException {
        underlyingStatement.setMaxRows(max);
    }

    @Override
    public void setEscapeProcessing(boolean enable) throws SQLException {
        underlyingStatement.setEscapeProcessing(enable);
    }

    @Override
    public int getQueryTimeout() throws SQLException {
        return underlyingStatement.getQueryTimeout();
    }

    @Override
    public void setQueryTimeout(int seconds) throws SQLException {
        underlyingStatement.setQueryTimeout(seconds);
    }

    @Override
    public void cancel() throws SQLException {
        underlyingStatement.cancel();
    }

    @Override
    public SQLWarning getWarnings() throws SQLException {
        return underlyingStatement.getWarnings();
    }

    @Override
    public void clearWarnings() throws SQLException {
        underlyingStatement.clearWarnings();
    }

    @Override
    public void setCursorName(String name) throws SQLException {
        underlyingStatement.setCursorName(name);
    }

    @Override
    public <U> U unwrap(Class<U> iface) throws SQLException {
        if (iface.isAssignableFrom(getClass())) {
            return iface.cast(this);
        }
        return underlyingStatement.unwrap(iface);
    }

    @Override
    public boolean isWrapperFor(Class<?> iface) throws SQLException {
        return iface.isAssignableFrom(getClass()) || underlyingStatement.isWrapperFor(iface);
    }

    /**
     * Apply SQL rewriting hooks to the given SQL statement.
     */
    protected String applySqlRewriting(String sql) {
        if (!config.isEnabled() || config.getRewriters().isEmpty()) {
            return sql;
        }

        String rewrittenSql = sql;
        for (var rewriter : config.getRewriters()) {
            try {
                rewrittenSql = rewriter.rewriteSql(rewrittenSql, proxyConnection);
            } catch (Exception e) {
                logger.warn("Error in SQL rewriter", e);
            }
        }
        return rewrittenSql;
    }

    /**
     * Execute an operation with logging.
     */
    protected <R> R executeWithLogging(String sql, SqlOperation<R> operation) throws SQLException {
        if (!config.isEnabled() || config.getLoggers().isEmpty()) {
            return operation.execute();
        }

        long startTime = System.currentTimeMillis();
        SQLException exception = null;
        R result = null;
        String rewrittenSql = applySqlRewriting(sql);
        
        try {
            result = operation.execute();
            return result;
        } catch (SQLException e) {
            exception = e;
            throw e;
        } finally {
            long endTime = System.currentTimeMillis();
            
            int rowCount = -1;
            if (result instanceof Integer) {
                rowCount = (Integer) result;
            }
            
            logStatement(sql, rewrittenSql, Collections.emptyList(), startTime, endTime, rowCount, exception);
        }
    }

    /**
     * Log a statement execution.
     */
    protected void logStatement(String originalSql, String rewrittenSql, List<Object> parameters, 
                              long startTime, long endTime, int rowCount, SQLException exception) {
        config.getLoggers().forEach(jdbcLogger -> {
            try {
                jdbcLogger.logStatement(originalSql, rewrittenSql, parameters, proxyConnection, 
                                      startTime, endTime, rowCount, exception);
            } catch (Exception e) {
                logger.warn("Error in JDBC logger while logging statement", e);
            }
        });
    }

    /**
     * Log a batch execution.
     */
    protected void logBatch(long startTime, long endTime, int[] updateCounts, SQLException exception) {
        if (!config.isEnabled() || config.getLoggers().isEmpty()) {
            return;
        }

        config.getLoggers().forEach(jdbcLogger -> {
            try {
                int batchSize = updateCounts != null ? updateCounts.length : 0;
                jdbcLogger.logBatch(getLastExecutedSql(), batchSize, proxyConnection, 
                                  startTime, endTime, updateCounts, exception);
            } catch (Exception e) {
                logger.warn("Error in JDBC logger while logging batch", e);
            }
        });
    }

    /**
     * Get the last executed SQL statement (to be overridden by subclasses).
     */
    protected abstract String getLastExecutedSql();

    /**
     * Functional interface for SQL operations.
     */
    @FunctionalInterface
    protected interface SqlOperation<R> {
        R execute() throws SQLException;
    }
}
